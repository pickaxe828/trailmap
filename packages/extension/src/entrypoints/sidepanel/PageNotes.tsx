import { Collapsible } from '@astryxdesign/core/Collapsible';
import { Heading } from '@astryxdesign/core/Heading';
import { Link } from '@astryxdesign/core/Link';
import { List, ListItem } from '@astryxdesign/core/List';
import { Text } from '@astryxdesign/core/Text';
import { VStack } from '@astryxdesign/core/VStack';
import type { Page } from '@trailmap/shared';

export function PageNotes({ summary, takeaways }: Pick<Page, 'summary' | 'takeaways'>) {
  return (
    <Collapsible trigger={<Text weight="semibold">Generated page notes</Text>} defaultIsOpen={false}>
      <VStack gap={2}>
        <Text as="p">{summary}</Text>
        <List density="compact" listStyle="disc" edge="flush" header={<Heading level={3}>Key takeaways</Heading>}>
          {takeaways.map((takeaway, index) => <ListItem key={index} label={<Text>{takeaway}</Text>} align="first-line" />)}
        </List>
        <Text type="supporting">Generated by your extraction provider.{' '}
          <Link hasUnderline href="/settings.html#sent-to-model" target="_blank">See what was sent</Link>
        </Text>
      </VStack>
    </Collapsible>
  );
}
